"""footprint_item.py — D36 footprint render layer.

A pyqtgraph GraphicsObject that draws per-level footprint data beside
candles. Two instances live on the chart (mirroring the D28.4 static/live
split):

- ``footprint_static`` — completed bars; regenerated only when footprint
  data for a completed bar arrives or the series/style changes.
- ``footprint_live`` — the forming bar only; refreshed by the 15s
  incremental service refresh, never by per-tick chart updates.

``regen_count`` mirrors ``CandlestickItem`` so AC-D36.4 can assert zero
static-layer regenerations on a tick burst.

Styles (owner decision 2026-10-13):
- ``classic`` — bid×ask bars: bid volume extends left from the candle
  centre, ask volume right. Volume-only.
- ``heatmap`` — heatmap-shaded candles: each price level is shaded by the
  selected metric. Metric selector: ``volume`` (bid+ask size, same buckets
  as classic) or ``count`` (per-level trade count — same tick pages, pure
  presentation switch, zero new requests).

Entries are ``(x, levels)`` with ``x`` the display-x of the bar and
``levels`` the service's ``{price: [bidVol, askVol, tradeVol, tradeCount]}``.
"""

from __future__ import annotations

import pyqtgraph as pg
from PyQt6.QtGui import QPicture, QPainter, QColor, QPen, QBrush
from PyQt6.QtCore import QRectF, QPointF, Qt

_BID_COLOR = QColor("#60a5fa")   # blue-400
_ASK_COLOR = QColor("#fbbf24")   # amber-400
_HEAT_COLOR = (255, 170, 40)     # amber heat


class FootprintItem(pg.GraphicsObject):
    STYLE_CLASSIC = "classic"
    STYLE_HEATMAP = "heatmap"
    METRIC_VOLUME = "volume"
    METRIC_COUNT = "count"

    def __init__(self):
        super().__init__()
        self._entries: list[tuple[float, dict]] = []
        self._style: str = self.STYLE_CLASSIC
        self._metric: str = self.METRIC_VOLUME
        self._half_width: float = 0.25
        self._picture = QPicture()
        # D36/AC-D36.4: render-call counter — the gate asserts the static
        # layer is never regenerated by forming-bar ticks.
        self.regen_count: int = 0

    # ── Public API ─────────────────────────────────────────────────────

    def set_data(self, entries: list[tuple[float, dict]], style: str,
                 metric: str, half_width: float) -> None:
        """Full rebuild (completed bars)."""
        self._entries = list(entries)
        self._style = style
        self._metric = metric
        self._half_width = max(half_width, 1e-9)
        self._generate()
        self.update()

    def clear(self) -> None:
        self._entries = []
        self._generate()
        self.update()

    # ── Rendering ──────────────────────────────────────────────────────

    def _level_value(self, vals: list) -> float:
        if self._metric == self.METRIC_COUNT:
            return float(vals[3])
        return float(vals[0]) + float(vals[1])

    def _generate(self):
        self.regen_count += 1
        self._picture = QPicture()
        if not self._entries:
            return
        p = QPainter(self._picture)
        p.setRenderHint(QPainter.RenderHint.Antialiasing, False)
        if self._style == self.STYLE_HEATMAP:
            self._draw_heatmap(p)
        else:
            self._draw_classic(p)
        p.end()

    def _draw_classic(self, p: QPainter):
        # Global max keeps bar widths comparable across the visible window.
        vmax = 0.0
        for _, levels in self._entries:
            for vals in levels.values():
                v = float(vals[0]) + float(vals[1])
                if v > vmax:
                    vmax = v
        if vmax <= 0:
            return
        bid_pen = QPen(_BID_COLOR)
        bid_pen.setCosmetic(True)
        ask_pen = QPen(_ASK_COLOR)
        ask_pen.setCosmetic(True)
        bid_brush = QBrush(_BID_COLOR)
        ask_brush = QBrush(_ASK_COLOR)
        hw = self._half_width
        for x, levels in self._entries:
            prices = sorted(levels)
            if len(prices) > 1:
                diffs = sorted(prices[i] - prices[i - 1]
                               for i in range(1, len(prices)))
                lh = diffs[len(diffs) // 2] * 0.4
            else:
                lh = hw * 0.1
            for price in prices:
                bid, ask = float(levels[price][0]), float(levels[price][1])
                if bid > 0:
                    w = (bid / vmax) * hw
                    p.setPen(bid_pen)
                    p.setBrush(bid_brush)
                    p.drawRect(QRectF(x - w, price - lh, w, lh * 2))
                if ask > 0:
                    w = (ask / vmax) * hw
                    p.setPen(ask_pen)
                    p.setBrush(ask_brush)
                    p.drawRect(QRectF(x, price - lh, w, lh * 2))

    def _draw_heatmap(self, p: QPainter):
        vmax = 0.0
        for _, levels in self._entries:
            for vals in levels.values():
                v = self._level_value(vals)
                if v > vmax:
                    vmax = v
        if vmax <= 0:
            return
        hw = self._half_width
        for x, levels in self._entries:
            prices = sorted(levels)
            if len(prices) > 1:
                diffs = sorted(prices[i] - prices[i - 1]
                               for i in range(1, len(prices)))
                lh = diffs[len(diffs) // 2] * 0.45
            else:
                lh = hw * 0.1
            for price in prices:
                v = self._level_value(levels[price])
                if v <= 0:
                    continue
                alpha = int(35 + 170 * (v / vmax))
                c = QColor(*_HEAT_COLOR, alpha)
                p.setPen(Qt.PenStyle.NoPen)
                p.setBrush(QBrush(c))
                p.drawRect(QRectF(x - hw, price - lh, hw * 2, lh * 2))

    # ── pyqtgraph overrides ────────────────────────────────────────────

    def paint(self, painter, option, widget):
        painter.drawPicture(0, 0, self._picture)

    def boundingRect(self):
        return QRectF(self._picture.boundingRect())
