"""
candlestick_item.py
Custom pyqtgraph GraphicsObject supporting 5 render modes:
  'candles'  — filled green/red bodies with wicks
  'hollow'   — outline-only bodies (TOS hollow candles)
  'heikin'   — Heikin-Ashi computed in the data layer
  'line'     — close-price line
  'area'     — close-price filled area
"""

from enum import Enum
from typing import List, Tuple, Optional
import pyqtgraph as pg
from PyQt6.QtGui import QPicture, QPainter, QColor, QPen, QBrush, QPainterPath
from PyQt6.QtCore import QRectF, QPointF, Qt

GREEN  = QColor('#34d399')  # emerald-400
RED    = QColor('#f87171')  # red-400
LINE_C = QColor('#60a5fa')  # blue-400 — used for line/area mode


class ChartMode(str, Enum):
    CANDLES = "candles"
    HOLLOW  = "hollow"
    HEIKIN  = "heikin"
    LINE    = "line"
    AREA    = "area"


def _compute_heikin(data: List[Tuple]) -> List[Tuple]:
    """
    data: list of (t, o, h, l, c)
    Returns transformed Heikin-Ashi (t, ha_o, ha_h, ha_l, ha_c).
    """
    result = []
    prev_ha_o, prev_ha_c = None, None
    for (t, o, h, l, c) in data:
        ha_c = (o + h + l + c) / 4
        ha_o = ((prev_ha_o + prev_ha_c) / 2) if prev_ha_o is not None else (o + c) / 2
        ha_h = max(h, ha_o, ha_c)
        ha_l = min(l, ha_o, ha_c)
        result.append((t, ha_o, ha_h, ha_l, ha_c))
        prev_ha_o, prev_ha_c = ha_o, ha_c
    return result


def capped_body_half_width(median_diff: float, base_half_width: float,
                           px_per_sec: float, floor_px: float = 4.0) -> float:
    """D42/S13: the one density-aware candle-body half-width rule.

    ``w = min(max(base_half_width, floor_px / 2 / px_per_sec), median_diff / 2)``

    With ``base_half_width = 0.325 * median_diff`` (the D6 formula: full body
    65 % of the spacing, 35 % gap) and ``pitch = median_diff * px_per_sec`` this
    is ``body = min(max(0.65 * pitch, floor_px), pitch)``.  ``floor_px`` is the
    legibility floor in ViewBox logical pixels — the unit ``px_per_sec`` yields
    and the unit the shipped ``min_w`` clamp already used.  The floor binds
    whenever the pitch allows it and yields to the pitch at higher density, so
    ``body <= pitch`` — a non-negative inter-bar gap — in every regime.  Pure:
    no Qt and no QApplication required.
    """
    if px_per_sec <= 0:
        return base_half_width
    floor_half_width = floor_px / 2.0 / px_per_sec
    return min(max(base_half_width, floor_half_width), median_diff / 2.0)


def _median_time_diff(data: List[Tuple]) -> float:
    """Median spacing between adjacent bar timestamps (display-x units)."""
    time_diffs = [data[i][0] - data[i - 1][0] for i in range(1, len(data))]
    time_diffs.sort()
    return time_diffs[len(time_diffs) // 2]


class CandlestickItem(pg.GraphicsObject):
    def __init__(self, data: List[Tuple], mode: ChartMode = ChartMode.CANDLES):
        super().__init__()
        self._raw_data: List[Tuple] = data
        self._mode = mode
        self._picture = QPicture()
        # D28.4: render-call counter — the 10-chart gate asserts the static
        # layer is never regenerated by forming-bar ticks.
        self.regen_count: int = 0
        # Optional precomputed candle half-width (D28.4): when set, skips the
        # O(n log n) median-spacing computation in _draw_candles.
        self._width_override: Optional[float] = None
        # D42/S14: the display-x pitch cached alongside the D28.4 width override
        # by the host, so the density cap does not have to re-run the sort.
        self._pitch: Optional[float] = None
        # Q-4: the display-x median bar spacing (data units) cached with the
        # width override. Unlike ``_pitch`` (pixels, and therefore only valid
        # for the zoom level it was computed at) this is zoom-invariant, so the
        # density cap stays correct when the host regenerates the picture after
        # a range change.
        self._spacing: Optional[float] = None
        # Q-4: the half-width actually baked into the last generated picture,
        # in display-x data units. The host reads it to decide whether a range
        # change actually changes the rendered body (skip when equal).
        self.last_body_half_width: float = 0.0
        self._generate()

    # ── Public API ─────────────────────────────────────────────────────────────

    def set_data(self, data: List[Tuple], mode: Optional[ChartMode] = None,
                 width: Optional[float] = None, pitch: Optional[float] = None,
                 spacing: Optional[float] = None):
        self._raw_data = data
        if mode is not None:
            self._mode = mode
        if width is not None:
            self._width_override = width
            # D42/S14: the display-x pitch travels with the D28.4 width override.
            # It is used only when an override is set; absent, _draw_candles
            # recomputes median_diff from data exactly as before.
            self._pitch = pitch
            # Q-4: the zoom-invariant display-x spacing travels with the
            # override too, so the density cap no longer depends on a pitch
            # measured at the (possibly stale) generation-time zoom.
            self._spacing = spacing
        self._generate()
        self.update()

    def set_mode(self, mode: ChartMode):
        self._mode = mode
        self._generate()
        self.update()

    # ── Rendering ─────────────────────────────────────────────────────────────

    def _generate(self):
        self.regen_count += 1
        self._picture = QPicture()
        if not self._raw_data:
            return

        p = QPainter(self._picture)
        p.setRenderHint(QPainter.RenderHint.Antialiasing, False)

        if self._mode in (ChartMode.CANDLES, ChartMode.HOLLOW):
            self._draw_candles(p, hollow=(self._mode == ChartMode.HOLLOW))
        elif self._mode == ChartMode.HEIKIN:
            self._draw_candles(p, hollow=False, data=_compute_heikin(self._raw_data))
        elif self._mode == ChartMode.LINE:
            self._draw_line(p)
        elif self._mode == ChartMode.AREA:
            self._draw_area(p)

        p.end()

    def _draw_candles(self, p: QPainter, hollow: bool, data: Optional[List[Tuple]] = None):
        data = data or self._raw_data
        # D28.4: the host may supply a precomputed half-width (cached at full
        # rebuild); otherwise compute from median bar spacing as before.
        # D42/S14: alongside that override the host may supply the display-x
        # pitch, so the cap recovers median_diff from pitch = median_diff *
        # px_per_sec without re-running the O(n log n) sort D28.4 removed.
        median_diff: Optional[float] = None
        if self._width_override is not None:
            w = self._width_override
            pitch = self._pitch
            # Q-4: the zoom-invariant spacing wins when the host supplies it;
            # ``pitch`` (px) is only a fallback for older callers because it is
            # tied to the zoom level it was measured at.
            median_diff = self._spacing
            if median_diff is None and pitch is None and len(data) > 1:
                # Override without a pitch: still derive the spacing from the
                # data so the density cap can bind.
                median_diff = _median_time_diff(data)
        elif len(data) > 1:
            # Use median time diff between bars to set width (e.g., 32.5% of spacing, gap 35%)
            median_diff = _median_time_diff(data)
            w = median_diff * 0.325  # half-width = 32.5% of spacing (gap 35%)
            pitch = None
        else:
            w = 0.25  # fallback for single bar
            pitch = None

        # Body pens — cosmetic 1px so border stays device-pixel stable
        green_pen   = QPen(GREEN); green_pen.setWidthF(1.0); green_pen.setCosmetic(True)
        red_pen     = QPen(RED);   red_pen.setWidthF(1.0); red_pen.setCosmetic(True)
        # Wick pens — cosmetic 1px body-coloured, behind the body
        wick_green = QPen(GREEN); wick_green.setWidthF(1.0); wick_green.setCosmetic(True); wick_green.setCapStyle(Qt.PenCapStyle.FlatCap)
        wick_red   = QPen(RED);   wick_red.setWidthF(1.0);   wick_red.setCosmetic(True); wick_red.setCapStyle(Qt.PenCapStyle.FlatCap)

        # D42/S13: apply the 4-px legibility floor through the one shared capped
        # helper instead of an unconditional min-width clamp, so the rendered body
        # never exceeds the inter-bar pitch (the floor yields at higher density and
        # the inter-bar gap is never negative).
        try:
            vb = self.getViewBox() if hasattr(self, "getViewBox") else None
            if vb is None:
                # fallback: parent ViewBox
                parent = self.parentItem()
                if parent is not None and hasattr(parent, "viewRange"):
                    vb = parent
            if vb is not None and hasattr(vb, "width") and vb.width() > 50:
                x_range = vb.viewRange()[0]
                x_span = x_range[1] - x_range[0]
                if x_span > 0:
                    px_per_sec = vb.width() / x_span
                    if median_diff is None:
                        if pitch is not None:
                            # D42/S14: pitch = median_diff * px_per_sec.
                            median_diff = pitch / px_per_sec
                        elif len(data) > 1:
                            median_diff = _median_time_diff(data)
                    if median_diff is not None:
                        w = capped_body_half_width(median_diff, w, px_per_sec)
        except Exception:
            pass

        # Q-4: the width actually baked into this picture (data units), so the
        # host can tell whether a range change would alter the rendered body.
        self.last_body_half_width = w

        green_brush = QBrush(GREEN)
        red_brush   = QBrush(RED)
        no_brush    = QBrush(QColor(0, 0, 0, 0))

        for (t, o, h, l, c) in data:
            bull = c >= o
            body_pen   = green_pen if bull else red_pen
            body_brush = (no_brush if hollow else (green_brush if bull else red_brush))
            wick_pen = wick_green if bull else wick_red
            # Wick behind body
            p.setPen(wick_pen)
            p.drawLine(QPointF(t, l), QPointF(t, h))
            # Body
            body_top    = max(o, c)
            body_bottom = min(o, c)
            body_h = body_top - body_bottom
            p.setPen(body_pen)
            p.setBrush(body_brush)
            if body_h < 0.0001:
                p.drawLine(QPointF(t - w, o), QPointF(t + w, o))
            else:
                p.drawRect(QRectF(t - w, body_bottom, w * 2, body_h))

    def _draw_line(self, p: QPainter):
        pen = QPen(LINE_C)
        pen.setWidthF(1.2)
        p.setPen(pen)
        pts = [QPointF(t, c) for (t, o, h, l, c) in self._raw_data]
        for i in range(1, len(pts)):
            p.drawLine(pts[i - 1], pts[i])

    def _draw_area(self, p: QPainter):
        if len(self._raw_data) < 2:
            return
        path = QPainterPath()
        first_t, _, _, _, first_c = self._raw_data[0]
        path.moveTo(first_t, 0)
        path.lineTo(first_t, first_c)
        for (t, o, h, l, c) in self._raw_data:
            path.lineTo(t, c)
        last_t = self._raw_data[-1][0]
        path.lineTo(last_t, 0)
        path.closeSubpath()

        fill = QColor(LINE_C)
        fill.setAlpha(40)
        p.setBrush(QBrush(fill))
        pen = QPen(LINE_C)
        pen.setWidthF(1.2)
        p.setPen(pen)
        p.drawPath(path)

    # ── pyqtgraph overrides ────────────────────────────────────────────────────

    def paint(self, painter, option, widget):
        painter.drawPicture(0, 0, self._picture)

    def boundingRect(self):
        return QRectF(self._picture.boundingRect())
